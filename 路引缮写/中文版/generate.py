def inject(html):
    import re
    m = re.search(r'data-page="(\d+)"', html)
    if not m:
        return html
    n = int(m.group(1))
    extra = (EXTRA.get(n) or "") + (MORE.get(n) or "") + (WAVE3.get(n) or "") + (WAVE4.get(n) or "")
    if not extra:
        return html
    mark = f'<footer class="pg">{n}/36</footer>'
    return html.replace(mark, f'<section class="thick">{extra}</section>\n{mark}', 1)

