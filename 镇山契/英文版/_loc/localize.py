def remaining_han(text: str) -> tuple[int, list[str]]:
    stripped = SVG_RE.sub("SVGDATA", text)
    # drop search keyword aliases (Chinese kept on purpose)
    stripped = re.sub(r"  const searchKeywords = Object\.freeze\(\[[\s\S]*?\]\);", "", stripped)
    # drop artifact spans
    stripped = re.sub(
        r'<span class="[^"]*zh-artifact[^"]*"[^>]*>[\s\S]*?</span>',
        "",
        stripped,
    )
    toks = sorted(set(re.findall(r"[\u4e00-\u9fff]+", stripped)), key=lambda x: (-len(x), x))
    total = sum(len(t) * stripped.count(t) for t in toks)
    return total, toks


