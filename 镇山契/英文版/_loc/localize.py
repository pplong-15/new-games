def protect_svg(text: str) -> tuple[str, list[str]]:
    held: list[str] = []

    def keep(m: re.Match[str]) -> str:
        held.append(m.group(0))
        return f"__SVG_{len(held)-1}__"

    return SVG_RE.sub(keep, text), held


def restore_svg(text: str, held: list[str]) -> str:
    for i, blob in enumerate(held):
        text = text.replace(f"__SVG_{i}__", blob)
    return text


def protect_aliases(text: str) -> tuple[str, str]:
    m = re.search(r"  const searchKeywords = Object\.freeze\(\[[\s\S]*?\]\);", text)
    if not m:
        raise SystemExit("searchKeywords block not found")
    token = "___SEARCH_KEYWORDS_BLOCK___"
    return text[: m.start()] + token + text[m.end() :], m.group(0)


def longest_replace(text: str, pairs: list[tuple[str, str]]) -> str:
    pairs = sorted(((a, b) for a, b in pairs if a and a != b), key=lambda x: len(x[0]), reverse=True)
    for zh, en in pairs:
        if zh in text:
            text = text.replace(zh, en)
    return text


